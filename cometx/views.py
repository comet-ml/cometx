def build_view(
    name: str,
    sections: Sequence[Section],
    filters: Optional[str] = None,
    table: Optional[str] = None,
    config: Optional[Dict[str, Any]] = None,
    auto_generate: bool = False,
    personal: bool = False,
) -> View:
    """Assemble sections into a ``View`` ready for ``create_view``.

    Args:
        name: the view's display name.
        sections: ``Section`` objects, top to bottom.
        filters: output of ``query_state()``, or None for no filtering.
        table: output of ``table_state()``, or None to keep the UI default.
        config: output of ``global_config()``.
        auto_generate: True lets Comet append auto-generated panels for
            newly logged metrics underneath your sections.
        personal: mark the view as personal (visible only to you).

    Returns:
        A ``View``. Pass it to ``API.create_view(workspace, project, view)`` or
        ``APIExperiment.create_view(view)``.
    """
    section_dicts = [s.to_dict() for s in sections]
    all_panels = [p for s in section_dicts for p in s["panels"]]

    v3 = {
        "layout": [],  # legacy top-level mirror; sections carry the real layout
        "globalConfig": config or global_config(),
        "sections": section_dicts,
        "autoGenerate": auto_generate,
        "isPersonalView": personal,
    }

    charts: Dict[str, Any] = {bucket: [] for bucket in _LEGACY_BUCKETS}
    for panel in all_panels:
        charts.setdefault(panel["chartType"], []).append(panel)
    charts["numberOfCharts"] = len(all_panels)

    return View(
        name=name,
        chart_state=json.dumps({"charts": charts, "layout": None}),
        query_state=filters if filters is not None else query_state(),
        table_state=table,
        v2={
            "toggles": {
                "DASHBOARD_TOGGLE": {"toggleId": "DASHBOARD_TOGGLE", "isToggled": True},
                "EXPERIMENT_TABLE_TOGGLE": {
                    "toggleId": "EXPERIMENT_TABLE_TOGGLE",
                    "isToggled": True,
                },
            }
        },
        v3=v3,
    )


def build_experiment_view(
    name: str,
    sections: Sequence[Section],
    x_axis: str = "step",
    smoothing: float = 0,
    transform_y: Optional[str] = None,
    sample_size: int = 100,
    auto_generate: bool = False,
    auto_refresh: bool = True,
    media_sort_by: str = "name",
    media_order: str = "desc",
    group_media: bool = False,
) -> View:
    """Assemble sections into a ``View`` for ``APIExperiment.create_view``.

    Experiment-scoped views are stored in the chart-template tables, which use a
    different envelope than project dashboards: everything lives under ``v2``
    (sections inside ``v2["panels"]``), and the per-tab display settings for
    images / text / audio / histograms / confusion matrices sit alongside them.

    Args:
        name: the view's display name.
        sections: ``Section`` objects -- the same ones ``build_view`` takes.
        x_axis: "step", "duration", "wall", or "epoch".
        smoothing: 0..1 curve smoothing applied to every chart.
        transform_y: None, "log", "ln", "sqrt".
        sample_size: max points fetched per curve.
        auto_generate: let Comet append auto panels for new metrics.
        auto_refresh: refresh the view while the run is live.
        media_sort_by / media_order / group_media: sorting of the image, audio
            and text tabs.

    Returns:
        A ``View`` to pass to ``APIExperiment.create_view(view)``. Do not set
        ``experiment_key`` -- ``create_view`` stamps it on for you.
    """
    media = {"groupBy": group_media, "orderBy": media_order, "sortBy": media_sort_by}
    v2 = {
        "template_name": name,
        "x_axis": x_axis,
        "smoothing": smoothing,
        "transformY": transform_y,
        "sampleSize": sample_size,
        "entire_row_charts": False,
        "charts": [],  # legacy per-experiment chart list; sections supersede it
        "outliers": {"percentile": 0, "isVisible": True},
        "panels": {
            "version": 5,
            "sections": [s.to_dict() for s in sections],
            "panels": [],
            "layout": [],
            "compareXAxis": x_axis,
            "autoGenerate": auto_generate,
            "isAutoRefreshEnabled": auto_refresh,
        },
        "autoGeneratedDraft": False,
        "deleteAutogenerated": False,
        "projectName": "",
        "project_id": "",
        "metricColors": [],
        "metricColorsV2": {
            "singleExperiment": {
                "isSingleExperimentColor": False,
                "colors": [],
                "singleExperimentColor": False,
            }
        },
        "lastUpdate": 0,
        "layout": [],
        "images": dict(media),
        "audio": dict(media),
        "text": {
            "groupBy": group_media,
            "orderBy": media_order,
            "sortBy": "step",
            "fullHeightToggle": False,
            "step": -1,
        },
        "confusionMatrix": {
            "assetsIds": [],
            "compareAssetsIds": [],
            "cellValue": "Counts",
            "colorDistribution": "Equal",
        },
        "histogram": {
            "groupBy": group_media,
            "ignoreOutliers": 0.1,
            "maxSteps": 50,
            "orderBy": media_order,
            "sortBy": "name",
        },
        "metrics": {"decimalsPrecision": None},
        "hyperParams": {"decimalsPrecision": None},
        "otherParams": {"decimalsPrecision": None},
    }
    return View(name=name, v2=v2)



class Section:
    """A titled, collapsible group of panels on a dashboard.

    Args:
        title: the section header shown in the UI.
        panels: panel dicts from the factories above.
        columns: panels per row (1, 2, 3, or 6). Panels flow left to right.
        expanded: whether the section starts open.
        height: row height in grid units (1 is the UI default, max 3).
    """

    def __init__(
        self,
        title: str,
        panels: Sequence[Dict[str, Any]] = (),
        columns: int = 3,
        expanded: bool = True,
        height: int = 1,
    ):
        if GRID_WIDTH % columns:
            raise ValueError("columns must divide %d evenly" % GRID_WIDTH)
        self.title = title
        self.panels = list(panels)
        self.columns = columns
        self.expanded = expanded
        self.height = height
        self.id = new_id()

    def add(self, *panels: Dict[str, Any]) -> "Section":
        """Append panels; returns self so calls can be chained."""
        self.panels.extend(panels)
        return self

    def layout(self) -> List[Dict[str, Any]]:
        """Compute the react-grid-layout entries for this section's panels."""
        width = GRID_WIDTH // self.columns
        entries = []
        for index, panel in enumerate(self.panels):
            entries.append(
                {
                    "i": panel["chartId"],
                    "x": (index % self.columns) * width,
                    "y": (index // self.columns) * self.height,
                    "w": width,
                    "h": self.height,
                    "minW": 2,
                    "maxH": 3,
                    "moved": False,
                    "static": False,
                }
            )
        return entries

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "title": self.title,
            "autogenerated": False,
            "expanded": self.expanded,
            "panels": self.panels,
            "layout": self.layout(),
        }



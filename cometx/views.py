def legend_key(
    value: str = "Name", label: Optional[str] = None, source: str = "log_other"
) -> Dict[str, Any]:
    """One entry of a chart's ``selectedLegendKeys``.

    Common combinations:
        legend_key("Name")                                  # experiment name
        legend_key("experimentTags", "Tags", "tags")        # tags
        legend_key("learning_rate", source="params")        # a hyperparameter
    """
    return {"value": value, "label": label or value, "source": source}


DEFAULT_LEGEND = [legend_key("Name")]



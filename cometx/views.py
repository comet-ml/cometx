"""
cometx.views -- a builder library for Comet dashboard Views.

Views are the saved dashboards and per-experiment chart layouts in the Comet UI.
This module builds them programmatically: import the panel factories, compose
them into ``Section`` objects, and hand the result to ``build_view()`` (project
dashboards) or ``build_experiment_view()`` (per-experiment views).

    from cometx.views import Section, build_view, line_panel, scalar_panel

    view = build_view(
        "My Dashboard",
        sections=[
            Section("At a glance", [scalar_panel("accuracy", aggregation="max")]),
            Section("Curves", [line_panel(["loss", "val_loss"], smoothing=0.6)]),
        ],
    )
    API().create_view(workspace, project_name, view)

The Comet SDK exposes four functions for working with saved dashboard views:

    API.get_views(workspace, project_name)      -> list[View]
    API.create_view(workspace, project_name, v) -> View     (project-level)
    APIExperiment.get_views()                   -> list[View]
    APIExperiment.create_view(view)             -> View     (experiment-level)

A ``View`` is mostly a carrier for the dashboard's serialized layout state, and
the interesting content lives in ``view.v3`` -- a dict of *sections*, each
holding *panels* plus a grid *layout*. This module provides typed-ish factories
for every panel type the dashboard supports, plus ``build_view()`` to assemble
sections into a ``View`` that the Comet UI renders correctly.

Schema notes (derived from views saved by the Comet UI):

  v3 = {
    "layout": [],              # legacy mirror of section[0]; safe to leave empty
    "globalConfig": {...},     # dashboard-wide x-axis / smoothing / sampling
    "sections": [
        {"id": "aB3xY9", "title": "Metrics", "autogenerated": False,
         "expanded": True, "panels": [ ... ], "layout": [ ... ]},
    ],
    "autoGenerate": False,     # True lets Comet append auto panels for new metrics
    "isPersonalView": False,
  }

  chart_state ("dashboardChartState") is the pre-sections legacy format: the
  same panel dicts bucketed by type. We emit it alongside v3 for compatibility
  with older backends and with code that reads the legacy field.

  query_state ("experimentQueryState") holds the filter/segment state.
  table_state ("reactGridTableState") holds the experiment table config.

Experiment-level views (the chart-template scope, written by
``APIExperiment.create_view``) use a *different* envelope: the sections live in
``view.v2["panels"]`` and the display settings sit at the top of ``v2``, with
``v3`` unused. ``build_view`` targets the project scope and
``build_experiment_view`` the experiment scope; sections and panels are
identical between the two.

Nothing here calls the network; ``build_view`` returns a plain ``View`` that you
pass to ``API.create_view`` or ``APIExperiment.create_view``.
"""


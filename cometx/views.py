# The dashboard grid is 6 units wide. A panel with w=2 is one third of a row.
GRID_WIDTH = 6

_ID_ALPHABET = string.ascii_letters + string.digits


def new_id(length: int = 6) -> str:
    """Return a random id in the same style the UI generates ('F5ReNw')."""
    return "".join(random.choice(_ID_ALPHABET) for _ in range(length))



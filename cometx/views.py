def global_config(
    x_axis: str = "step",
    smoothing: float = 0,
    transform_y: Optional[str] = None,
    outliers: str = "show",
    sample_size: int = 100,
) -> Dict[str, Any]:
    """Dashboard-wide defaults applied to every non-``locked`` panel."""
    return {
        "selectedXAxis": x_axis,
        "transformY": transform_y,
        "smoothingY": smoothing,
        "selectedOutliers": outliers,
        "sampleSize": sample_size,
    }


def table_state(
    columns: Sequence[str] = (),
    sort_by: Optional[str] = None,
    descending: bool = True,
    page_size: int = 25,
    decimals: int = 6,
    visible: bool = True,
    column_width: int = 150,
) -> str:
    """Serialize the experiment-table configuration (``reactGridTableState``).

    Args:
        columns: column ids, in display order. Metric and parameter names work
            directly; UI columns include "Name", "duration", "experimentTags",
            "end_server_timestamp", "user_name".
        sort_by: column to sort on.
    """
    fixed = ["pinned", "singleExperimentBtn", "isVisibleOnDashboard"]
    ordered = fixed + [c for c in columns if c not in fixed]
    state = {
        "columnGrouping": [],
        "columnOrders": ordered,
        "columnSorting": (
            [{"columnName": sort_by, "direction": "desc" if descending else "asc"}]
            if sort_by
            else []
        ),
        "columnWidths": [
            {"columnName": c, "width": column_width} for c in ordered if c not in fixed
        ],
        "decimalsPrecision": decimals,
        "expandedGroups": [],
        "isVisible": visible,
        "pageSize": page_size,
        "selection": [],
        "hiddenExperiments": [],
    }
    return json.dumps(state)


def rule(
    field: str,
    operator: str,
    value: Any,
    source: str = "metrics",
    type_: Optional[str] = None,
) -> Dict[str, Any]:
    """One filter condition.

    Args:
        field: metric / parameter / column name.
        operator: "greater", "less", "equal", "not_equal", "contains",
            "not_contains", "is_not_empty", "begins_with".
        source: "metrics", "params", "log_other", "tags", "metadata".
        type_: value type -- inferred from ``value`` when omitted
            ("double", "string", "boolean").
    """
    if type_ is None:
        if isinstance(value, bool):
            type_ = "boolean"
        elif isinstance(value, (int, float)):
            type_ = "double"
        else:
            type_ = "string"
    return {
        "type": type_,
        "field": field,
        "source": source,
        "value": value,
        "operator": operator,
    }


def all_of(*rules: Dict[str, Any]) -> Dict[str, Any]:
    """AND-group of rules; use as one branch inside ``query_state``."""
    return {"condition": "AND", "rules": list(rules)}


def any_of(*groups: Dict[str, Any]) -> Dict[str, Any]:
    """OR of AND-groups -- the shape the filter builder produces."""
    return {"condition": "OR", "rules": list(groups) or [all_of()]}


def query_state(
    rules_tree: Optional[Dict[str, Any]] = None, segment_id: str = ""
) -> str:
    """Serialize the filter state (``experimentQueryState``).

    Example:
        query_state(any_of(all_of(rule("accuracy", "greater", 0.9))))
    """
    return json.dumps(
        {
            "activeSegment": {"segment_id": segment_id},
            "rulesTree": rules_tree or any_of(),
            "filters": [],
        }
    )



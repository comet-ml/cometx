def describe_view(view: View, indent: str = "") -> str:
    """Render a human-readable outline of a View's sections and panels."""
    lines = ["%s%s" % (indent, view.name)]
    meta = []
    if view.view_source:
        meta.append(view.view_source)
    if view.template_id:
        meta.append("id=%s" % view.template_id)
    if view.experiment_key:
        meta.append("experiment=%s" % view.experiment_key[:8])
    if view.project_default:
        meta.append("project default")
    if meta:
        lines.append("%s  [%s]" % (indent, ", ".join(meta)))

    sections = None
    if isinstance(view.v3, dict):
        sections = view.v3.get("sections")
    if not sections and isinstance(view.v2, dict):
        # Experiment-scoped view: sections live under v2["panels"].
        sections = (view.v2.get("panels") or {}).get("sections")
    if sections:
        for section in sections:
            flag = " (auto)" if section.get("autogenerated") else ""
            lines.append("%s  - section %r%s" % (indent, section.get("title"), flag))
            for panel in section.get("panels", []):
                lines.append("%s      * %s" % (indent, _panel_label(panel)))
    else:
        # Older view: read the legacy bucketed chart_state.
        try:
            charts = json.loads(view.chart_state or "{}").get("charts", {})
        except ValueError:
            charts = {}
        panels = [p for v in charts.values() if isinstance(v, list) for p in v]
        if panels:
            lines.append("%s  - (legacy chart_state, no sections)" % indent)
            for panel in panels:
                lines.append("%s      * %s" % (indent, _panel_label(panel)))
        else:
            lines.append("%s  - (no panels)" % indent)

    try:
        tree = json.loads(view.query_state or "{}").get("rulesTree", {})
    except ValueError:
        tree = {}
    conditions = [r for group in tree.get("rules", []) for r in group.get("rules", [])]
    for condition in conditions:
        lines.append(
            "%s  filter: %s %s %r"
            % (
                indent,
                condition.get("field"),
                condition.get("operator"),
                condition.get("value"),
            )
        )
    return "\n".join(lines)


def _panel_label(panel: Dict[str, Any]) -> str:
    kind = panel.get("chartType", "?")
    name = panel.get("chartName") or panel.get("instanceName") or ""
    detail = (
        panel.get("metricNames")
        or panel.get("metricName")
        or panel.get("fileName")
        or panel.get("images")
        or panel.get("params")
        or ""
    )
    label = "%-9s %s" % (kind, name)
    return "%s  %s" % (label.rstrip(), detail) if detail else label.rstrip()
